#!/usr/bin/env bash
set -euo pipefail
. "${BASH_SOURCE[0]%/*}/run-in-nix-env" "coreutils jq" "$@"

# Print the package versions table for docs/introduction.md, generated from versions.json.
# Usage:
#   helper/gen-docs-versions.sh > docs/versions-table.md
# helper/update-flake.sh runs this after it writes versions.json.

cd "${BASH_SOURCE[0]%/*}/.."

echo '<!-- Generated by helper/gen-docs-versions.sh from versions.json. Do not edit. -->'
echo
echo '| Package | Version | Channel |'
echo '|---|---|---|'
jq -r 'to_entries[] | "| `\(.key)` | \(.value.version) | \(.value.channel) |"' versions.json
