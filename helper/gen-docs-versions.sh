#!/usr/bin/env bash
set -euo pipefail
. "${BASH_SOURCE[0]%/*}/run-in-nix-env" "coreutils jq" "$@"

# Print the package versions table for docs/introduction.md, generated from versions.json.
# Each version links to the release notes or tag of the package.
# Usage:
#   helper/gen-docs-versions.sh > docs/versions-table.md
# helper/update-flake.sh runs this after it writes versions.json.
#
# Add a link below when you add a package to versions.json. The script fails for
# packages without a link.

cd "${BASH_SOURCE[0]%/*}/.."

echo '<!-- Generated by helper/gen-docs-versions.sh from versions.json. Do not edit. -->'
echo
echo '| Package | Version | Channel |'
echo '|---|---|---|'
jq -r '
  # Link templates. @VERSION@ is the package version. @REV@ is the part of the version
  # after the last `-` (the lightningd/plugins revision). @CLN@ is the clightning version.
  def gh($repo; $tagPrefix): "https://github.com/\($repo)/releases/tag/\($tagPrefix)@VERSION@";
  def plugin($dir): "https://github.com/lightningd/plugins/tree/@REV@/\($dir)";
  def clnPlugin($dir): "https://github.com/ElementsProject/lightning/tree/v@CLN@/plugins/\($dir)";

  {
    "bitcoin": "https://bitcoincore.org/en/releases/@VERSION@/",
    "bitcoind": "https://bitcoincore.org/en/releases/@VERSION@/",
    "btcpayserver": gh("btcpayserver/btcpayserver"; "v"),
    "charge-lnd": gh("accumulator/charge-lnd"; "v"),
    "clboss": gh("ksedgwic/clboss"; "v"),
    "clightning": gh("ElementsProject/lightning"; "v"),
    "clightning-plugins/clnrest": clnPlugin("rest-plugin"),
    "clightning-plugins/currencyrate": clnPlugin("currencyrate-plugin"),
    "clightning-plugins/feeadjuster": plugin("feeadjuster"),
    "clightning-plugins/monitor": plugin("monitor"),
    "clightning-plugins/rebalance": plugin("rebalance"),
    "clightning-plugins/zmq": plugin("cl-zmq"),
    "electrs": gh("romanz/electrs"; "v"),
    "extra-container": gh("extra-container/extra-container"; "v"),
    "fulcrum": gh("cculianu/Fulcrum"; "v"),
    "hwi": gh("bitcoin-core/HWI"; ""),
    "lnd": gh("lightningnetwork/lnd"; "v"),
    "lndconnect": gh("LN-Zap/lndconnect"; "v"),
    "lndinit": gh("lightninglabs/lndinit"; "v"),
    "mempool-backend": gh("mempool/mempool"; "v"),
    "mempool-frontend": gh("mempool/mempool"; "v"),
    "mempool-rust-gbt": gh("mempool/mempool"; "v"),
    "nbxplorer": gh("btcpayserver/NBXplorer"; "v"),
    "rtl": gh("Ride-The-Lightning/RTL"; "v"),
    "trustedcoin": gh("nbd-wtf/trustedcoin"; "v")
  } as $links
  | .clightning.version as $cln
  | to_entries[]
  | .key as $name
  | .value as $pkg
  | ($links[$name] // error("No release link for \($name). Add it to helper/gen-docs-versions.sh."))
  | split("@VERSION@") | join($pkg.version)
  | split("@REV@") | join($pkg.version | split("-") | last)
  | split("@CLN@") | join($cln)
  | "| `\($name)` | [\($pkg.version)](\(.)) | \($pkg.channel) |"
' versions.json
